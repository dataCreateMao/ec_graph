import argparse
import json
import sys
from pathlib import Path

import evaluate
import torch
from datasets import load_from_disk
from transformers import (
    AutoModelForTokenClassification,
    AutoTokenizer,
    DataCollatorForTokenClassification,
    EvalPrediction,
    Trainer,
    TrainingArguments,
)

# 允许直接以脚本方式运行：自动将 src 加入导入路径
SRC_DIR = Path(__file__).resolve().parents[1]
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from configuration.config import *


def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate NER model on test split.")
    parser.add_argument(
        "--model-dir",
        type=str,
        default=str(CHECKPOINT_DIR / NER_DIR / "best_model"),
        help="Model directory generated by train.py",
    )
    parser.add_argument(
        "--test-dir",
        type=str,
        default=str(PROCESSED_DATA_DIR / "test"),
        help="Dataset directory saved by preprocess.py (save_to_disk)",
    )
    return parser.parse_args()


def main():
    args = parse_args()

    model_dir = Path(args.model_dir)
    test_dir = Path(args.test_dir)

    if not model_dir.exists():
        raise FileNotFoundError(f"Model dir not found: {model_dir}")
    if not test_dir.exists():
        raise FileNotFoundError(f"Test dataset dir not found: {test_dir}")

    numpy_available_in_torch = True
    try:
        _ = torch.zeros(1).numpy()
    except Exception:
        numpy_available_in_torch = False

    if not numpy_available_in_torch:
        raise RuntimeError(
            "Torch-NumPy bridge is unavailable in current environment, cannot run Trainer.evaluate(). "
            "Please use a NumPy/Torch compatible env for eval (e.g. numpy<2 with torch 2.2.x, or newer torch)."
        )

    tokenizer = AutoTokenizer.from_pretrained(str(model_dir))
    model = AutoModelForTokenClassification.from_pretrained(str(model_dir))
    test_dataset = load_from_disk(str(test_dir))

    data_collator = DataCollatorForTokenClassification(
        tokenizer=tokenizer,
        padding=True,
        return_tensors="pt",
    )

    seqeval_metric = evaluate.load("seqeval")

    def compute_metrics(p: EvalPrediction):
        logits = p.predictions
        preds = logits.argmax(axis=-1)
        labels = p.label_ids

        unpad_labels = []
        unpad_preds = []
        for label, pred in zip(labels, preds):
            unpad_label = label[label != -100]
            unpad_pred = pred[label != -100]
            unpad_labels.append([model.config.id2label[idx] for idx in unpad_label])
            unpad_preds.append([model.config.id2label[idx] for idx in unpad_pred])
        return seqeval_metric.compute(predictions=unpad_preds, references=unpad_labels)

    eval_args = TrainingArguments(
        output_dir=str(CHECKPOINT_DIR / NER_DIR / "eval_tmp"),
        per_device_eval_batch_size=BATCH_SIZE,
        report_to=[],
    )
    trainer = Trainer(
        model=model,
        args=eval_args,
        eval_dataset=test_dataset,
        data_collator=data_collator,
        compute_metrics=compute_metrics,
    )

    metrics = trainer.evaluate()
    print("[INFO] Eval metrics:")
    print(json.dumps(metrics, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
